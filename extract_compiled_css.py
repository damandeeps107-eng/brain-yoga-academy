#!/usr/bin/env python3
"""
Extract compiled Tailwind CSS from browser runtime so we can remove
cdn.tailwindcss.com (3.5MB runtime compiler) entirely!
"""
import subprocess, time, json, urllib.request, asyncio, websockets

async def extract_css():
    cmd = [
        '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
        '--headless=new',
        '--disable-gpu',
        '--remote-debugging-port=9222',
        'about:blank'
    ]
    proc = subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    await asyncio.sleep(1.2)
    
    tabs = json.loads(urllib.request.urlopen('http://localhost:9222/json').read())
    ws_url = tabs[0]['webSocketDebuggerUrl']
    
    async with websockets.connect(ws_url) as ws:
        await ws.send(json.dumps({'id': 1, 'method': 'Page.enable'}))
        await ws.send(json.dumps({'id': 2, 'method': 'Runtime.enable'}))
        
        # Navigate to local busy-minds.html
        local_path = "file:///Users/user/.gemini/antigravity/scratch/brain-yoga-landing/busy-minds.html"
        await ws.send(json.dumps({'id': 3, 'method': 'Page.navigate', 'params': {'url': local_path}}))
        
        # Wait 3 seconds for Tailwind to finish compiling styles
        await asyncio.sleep(3.0)
        
        # Extract all style tag contents generated by Tailwind
        eval_expr = """
        (function() {
            var css = [];
            var styles = document.querySelectorAll('style');
            for (var i = 0; i < styles.length; i++) {
                css.push(styles[i].textContent || '');
            }
            return css.join('\\n');
        })()
        """
        await ws.send(json.dumps({
            'id': 4,
            'method': 'Runtime.evaluate',
            'params': {'expression': eval_expr, 'returnByValue': True}
        }))
        
        resp = await ws.recv()
        while True:
            data = json.loads(resp)
            if data.get('id') == 4:
                css_result = data.get('result', {}).get('result', {}).get('value', '')
                print(f"Extracted total CSS: {len(css_result)} characters ({len(css_result)/1024:.1f} KB)")
                with open('/Users/user/.gemini/antigravity/scratch/brain-yoga-landing/compiled_tailwind.css', 'w') as f:
                    f.write(css_result)
                print("Saved to compiled_tailwind.css")
                break
            resp = await ws.recv()
            
    proc.terminate()

asyncio.run(extract_css())
